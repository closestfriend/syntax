import JSZip from 'jszip';
import { DesignSystem, GeneratedAsset } from '../types/designSystem';

/**
 * Generate W3C Design Tokens Community Group (DTCG) standard JSON format
 * Supported by Tokens Studio for Figma, Figma Tokens plugin, and Style Dictionary.
 */
export function generateFigmaTokensJson(system: DesignSystem): string {
  const dtcgTokens: Record<string, any> = {
    $name: system.identity.name,
    $description: system.identity.description,
    color: {},
    typography: {},
    spacing: {},
    borderRadius: {},
    boxShadow: {},
  };

  // Colors
  system.colors.palette.forEach((token) => {
    const parts = (token.figmaTokenPath || `color/${token.category}/${token.name}`).split('/');
    let current = dtcgTokens;
    for (let i = 0; i < parts.length - 1; i++) {
      const part = parts[i];
      current[part] = current[part] || {};
      current = current[part];
    }
    const lastKey = parts[parts.length - 1];
    current[lastKey] = {
      $value: token.hex,
      $type: 'color',
      $description: `${token.role}. Contrast: ${token.contrastRatio || 'N/A'}. WCAG: ${token.wcagPass ? 'PASS' : 'WARN'}`,
    };
  });

  // Typography
  system.typography.steps.forEach((step) => {
    const slug = step.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    dtcgTokens.typography[slug] = {
      $type: 'typography',
      $value: {
        fontFamily: system.typography.fontFamilies.sans,
        fontSize: step.size,
        fontWeight: step.weight,
        lineHeight: step.lineHeight,
        letterSpacing: step.letterSpacing || '0px',
      },
      $description: step.cssClass,
    };
  });

  // Spacing
  system.spatial.spacingScale.forEach((sp) => {
    dtcgTokens.spacing[sp.token] = {
      $value: sp.pixels,
      $type: 'dimension',
      $description: `Rem equivalent: ${sp.rem}`,
    };
  });

  // Radii
  system.spatial.radii.forEach((r) => {
    dtcgTokens.borderRadius[r.token] = {
      $value: r.value,
      $type: 'borderRadius',
      $description: r.role,
    };
  });

  // Shadows
  system.spatial.shadows.forEach((sh) => {
    dtcgTokens.boxShadow[sh.token] = {
      $value: sh.value,
      $type: 'boxShadow',
      $description: sh.style || '',
    };
  });

  return JSON.stringify(dtcgTokens, null, 2);
}

/**
 * Generate Tailwind CSS configuration (v3/v4 theme extend)
 */
export function generateTailwindConfig(system: DesignSystem): string {
  const colorMap: Record<string, string> = {};
  system.colors.palette.forEach((c) => {
    const key = c.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    colorMap[key] = c.hex;
  });

  return `/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: '${system.identity.mode === 'light' ? 'class' : 'media'}',
  content: [
    './src/**/*.{js,ts,jsx,tsx,vue,html}',
  ],
  theme: {
    extend: {
      colors: {
        // Semantic Surfaces
        canvas: '${system.colors.surfaces.canvas}',
        surface: '${system.colors.surfaces.surface}',
        'surface-elevated': '${system.colors.surfaces.elevated}',
        'surface-border': '${system.colors.surfaces.border}',
        'text-primary': '${system.colors.surfaces.textPrimary}',
        'text-secondary': '${system.colors.surfaces.textSecondary}',
        // Extracted Palette
${Object.entries(colorMap)
  .map(([k, v]) => `        '${k}': '${v}',`)
  .join('\n')}
      },
      fontFamily: {
        sans: ['${system.typography.fontFamilies.sans}', 'sans-serif'],
        display: ['${system.typography.fontFamilies.display}', 'sans-serif'],
        mono: ['${system.typography.fontFamilies.mono || 'monospace'}', 'monospace'],
      },
      spacing: {
${system.spatial.spacingScale.map((s) => `        '${s.token.replace('space-', '')}': '${s.pixels}',`).join('\n')}
      },
      borderRadius: {
${system.spatial.radii.map((r) => `        '${r.token.replace('radius-', '')}': '${r.value}',`).join('\n')}
      },
      transitionTimingFunction: {
        'system-default': '${system.spatial.motion.easingDefault}',
      },
    },
  },
  plugins: [],
};
`;
}

/**
 * Generate standard CSS Variables (:root)
 */
export function generateCssVariables(system: DesignSystem): string {
  const lines: string[] = [
    `/* ======================================================== */`,
    `/* DESIGN SYSTEM: ${system.identity.name.toUpperCase()} */`,
    `/* Generated by SYNTAX Synthesis Engine                     */`,
    `/* ======================================================== */`,
    `:root {`,
    `  /* Surfaces & Canvas */`,
    `  --color-canvas: ${system.colors.surfaces.canvas};`,
    `  --color-surface: ${system.colors.surfaces.surface};`,
    `  --color-surface-elevated: ${system.colors.surfaces.elevated};`,
    `  --color-border: ${system.colors.surfaces.border};`,
    `  --color-text-primary: ${system.colors.surfaces.textPrimary};`,
    `  --color-text-secondary: ${system.colors.surfaces.textSecondary};`,
    ``,
    `  /* Core Palette */`,
  ];

  system.colors.palette.forEach((c) => {
    const slug = c.name.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    lines.push(`  --color-${slug}: ${c.hex}; /* ${c.role} */`);
  });

  lines.push(``, `  /* Typography Families */`);
  lines.push(`  --font-sans: '${system.typography.fontFamilies.sans}', sans-serif;`);
  lines.push(`  --font-display: '${system.typography.fontFamilies.display}', sans-serif;`);
  if (system.typography.fontFamilies.mono) {
    lines.push(`  --font-mono: '${system.typography.fontFamilies.mono}', monospace;`);
  }

  lines.push(``, `  /* Spacing Scale */`);
  system.spatial.spacingScale.forEach((s) => {
    lines.push(`  --${s.token}: ${s.pixels};`);
  });

  lines.push(``, `  /* Border Radii */`);
  system.spatial.radii.forEach((r) => {
    lines.push(`  --${r.token}: ${r.value};`);
  });

  lines.push(``, `  /* Motion Easing & Durations */`);
  lines.push(`  --ease-system: ${system.spatial.motion.easingDefault};`);
  lines.push(`  --duration-quick: ${system.spatial.motion.durationQuick};`);
  lines.push(`  --duration-standard: ${system.spatial.motion.durationStandard};`);

  lines.push(`}`);
  return lines.join('\n');
}

/**
 * Generate TypeScript Declaration File
 */
export function generateTypeScriptDefinitions(system: DesignSystem): string {
  return `/**
 * Type definitions for ${system.identity.name}
 * Generated automatically by SYNTAX Synthesis Engine
 */

export type ColorTokenName =
${system.colors.palette.map((c) => `  | '${c.name}'`).join('\n')};

export type SpacingTokenName =
${system.spatial.spacingScale.map((s) => `  | '${s.token}'`).join('\n')};

export type RadiusTokenName =
${system.spatial.radii.map((r) => `  | '${r.token}'`).join('\n')};

export type TypographyStepName =
${system.typography.steps.map((t) => `  | '${t.name}'`).join('\n')};

export interface DesignTokens {
  colors: Record<ColorTokenName, string>;
  spacing: Record<SpacingTokenName, string>;
  radii: Record<RadiusTokenName, string>;
}
`;
}

/**
 * Generate Markdown Design System Architecture Spec Sheet
 */
export function generateMarkdownSpec(system: DesignSystem): string {
  return `# ${system.identity.name} // DESIGN SYSTEM SPECIFICATION

> **Archetype:** ${system.identity.archetype}  
> **Tagline:** ${system.identity.tagline}  
> **Theme Mode:** ${system.identity.mode.toUpperCase()}  

---

## 1. Brand Concept & Visual Ethos
${system.identity.description}

### Guiding Principles:
${system.identity.visualEthos.map((e) => `- **${e}**`).join('\n')}

---

## 2. Color Architecture & WCAG Compliance

| Token Name | Category | Hex | Role | Contrast vs Canvas | WCAG AA |
| :--- | :--- | :--- | :--- | :--- | :--- |
${system.colors.palette
  .map(
    (c) =>
      `| **${c.name}** | \`${c.category}\` | \`${c.hex}\` | ${c.role} | ${c.contrastRatio || 'N/A'} | ${
        c.wcagPass ? 'PASS' : 'WARN'
      } |`
  )
  .join('\n')}

---

## 3. Typography Scale (${system.typography.scaleRatio})

- **Sans Body:** ${system.typography.fontFamilies.sans}
- **Display:** ${system.typography.fontFamilies.display}
- **Monospace:** ${system.typography.fontFamilies.mono || 'Standard Mono'}

| Step | Size | Line Height | Weight | Tailwind Class |
| :--- | :--- | :--- | :--- | :--- |
${system.typography.steps
  .map((s) => `| **${s.name}** | \`${s.size}\` | \`${s.lineHeight}\` | \`${s.weight}\` | \`${s.cssClass}\` |`)
  .join('\n')}

---

## 4. Components Catalog
${system.components
  .map(
    (c) => `### ${c.name} (\`${c.category}\`)
${c.description}
- **Figma Token Path:** \`${c.figmaTokens || 'comp/' + c.id}\`
`
  )
  .join('\n')}
`;
}

/**
 * Build and trigger client-side download of a unified .zip archive
 */
export async function downloadDesignSystemZip(system: DesignSystem, assets?: GeneratedAsset[]): Promise<void> {
  const zip = new JSZip();
  const folderName = `${system.identity.slug || 'design-system'}-package`;
  const root = zip.folder(folderName);
  if (!root) return;

  // 1. Tokens Studio / Figma JSON
  root.file('tokens.json', generateFigmaTokensJson(system));

  // 2. Tailwind Config
  root.file('tailwind.config.js', generateTailwindConfig(system));

  // 3. CSS Variables
  root.file('variables.css', generateCssVariables(system));

  // 4. TypeScript Definitions
  root.file('tokens.d.ts', generateTypeScriptDefinitions(system));

  // 5. Documentation
  root.file('README.md', generateMarkdownSpec(system));

  // 6. React Components folder
  const reactFolder = root.folder('components-react');
  if (reactFolder) {
    system.components.forEach((c) => {
      const fileName = `${c.id.replace(/[^a-zA-Z0-9]/g, '-')}.tsx`;
      reactFolder.file(fileName, c.reactCode);
    });
  }

  // 7. Vue Components folder
  const vueFolder = root.folder('components-vue');
  if (vueFolder) {
    system.components.forEach((c) => {
      const fileName = `${c.id.replace(/[^a-zA-Z0-9]/g, '-')}.vue`;
      vueFolder.file(fileName, c.vueCode);
    });
  }

  // 8. Generated Design System Image Assets (if any)
  if (assets && assets.length > 0) {
    const assetsFolder = root.folder('brand-assets');
    if (assetsFolder) {
      assets.forEach((ast, idx) => {
        let base64Data = ast.imageUrl;
        if (base64Data.includes(';base64,')) {
          base64Data = base64Data.split(';base64,')[1];
        }
        const fileName = `${ast.name.toLowerCase().replace(/[^a-z0-9]/g, '-')}-${idx + 1}.png`;
        assetsFolder.file(fileName, base64Data, { base64: true });
      });
    }
  }

  // Generate and download
  const blob = await zip.generateAsync({ type: 'blob' });
  const downloadUrl = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = downloadUrl;
  a.download = `${folderName}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(downloadUrl);
}
